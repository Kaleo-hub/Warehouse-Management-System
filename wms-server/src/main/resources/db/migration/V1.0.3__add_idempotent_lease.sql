-- =============================================================================
-- 幂等记录表：给「处理中」加一个租约到期时间
-- -----------------------------------------------------------------------------
-- 背景（这是个真实的坑）：
--   抢位记录是【独立提交】的（必须这样，否则别的线程看不到它，去重就失效了），
--   于是「抢完位、还没销登记」这个窗口里的记录不受任何事务保护。
--   如果进程在这个窗口里死了（重启 / OOM / kill -9），那行记录就永远停在
--   status=0（处理中），之后所有带同一个 key 的请求都会被 10007 挡住 ——
--   用户明明什么都没做成，系统却一直说「请勿重复提交」。
--
-- 修法：让「处理中」不是无限期的，而是一份【租约】。
--   抢位时写 locked_until = 现在 + 30 秒；
--   后来者读到 status=0 时先看租约：
--     没过期 → 人家确实在跑，拒绝（10007）
--     已过期 → 判定持锁进程已经不在了，用 CAS 接手重试
--
-- 为什么索引建在 (status, locked_until)：
--   ① 接手那一步按主键 idempotent_key 走唯一索引，用不到这个
--   ② 兜底任务要扫「status=0 且租约早就过期」的行，正好走这个联合索引
--      （等值列 status 在前，范围列 locked_until 在后）
--
-- 注意：Flyway 会校验 checksum，已执行过的版本不能改，只能新增版本号。
-- =============================================================================

ALTER TABLE `idempotent_record`
    ADD COLUMN `locked_until` datetime(3) NULL
        COMMENT '处理中租约到期时间。过期说明持锁的进程已经不在了，允许别人接手' AFTER `status`,
    ADD KEY `idx_status_locked` (`status`, `locked_until`);