-- =============================================================================
-- 幂等记录表：补一个「失败原因」字段
-- -----------------------------------------------------------------------------
-- 背景：idempotent_record 建表时只留了 result_snapshot（成功结果快照）。
-- 实际上失败那一支也需要留下原因：
--   1. 排查问题时要能看出「上次为什么失败」
--   2. status=2（失败）的记录允许重试，但得让人知道上一次失败在哪一步
-- 所以补一个独立的 error_msg，而不是把错误信息塞进 result_snapshot ——
-- 那个字段的语义是「用来重放的成功响应」，混进错误信息会让它变得没法信任。
--
-- 注意：Flyway 会校验 checksum，已执行过的版本不能改，只能新增版本号。
-- =============================================================================

ALTER TABLE `idempotent_record`
    ADD COLUMN `error_msg` varchar(255) NULL COMMENT '失败原因（status=2 时有值）' AFTER `result_snapshot`;