-- =============================================================================
-- 出库红冲（BR-011：已发货的单据不可撤销，只能开反向单）
-- -----------------------------------------------------------------------------
-- 为什么不把已发货的单直接改回未发货：
-- 货已经出库、账已经记了。改回去等于假装没发生过 ——
-- 库存流水里会留下一条对不上的记录，谁也说不清这批货到底出没出。
-- 正确做法是【再开一张反向单】：原单保持 SHIPPED 不动（历史事实），
-- 新单把它冲掉，两张单一起构成完整凭证链。财务上这叫红冲。
--
--   reverse_of_id  红冲单指向被冲掉的原单
--   reversed_by_id 原单指向冲掉它的红冲单（原单上能直接看到「被谁冲了」）
--   uk_reverse_of  唯一索引保证一张原单只能被红冲一次
--                  （MySQL 唯一索引允许多个 NULL，非红冲单不受影响）
-- =============================================================================

ALTER TABLE `outbound_order`
    ADD COLUMN `reverse_of_id`  bigint unsigned NULL COMMENT '红冲的原单ID（本单是它的反向单）' AFTER `status`,
    ADD COLUMN `reversed_by_id` bigint unsigned NULL COMMENT '被哪张红冲单冲掉的' AFTER `reverse_of_id`,
    ADD UNIQUE KEY `uk_reverse_of` (`reverse_of_id`);
