/** 单据号：IN + yyyyMMdd + 6 位序号 */
export function nextOrderNo() {
  const d = new Date()
  const ymd = `${d.getFullYear()}${String(d.getMonth() + 1).padStart(2, '0')}${String(
    d.getDate(),
  ).padStart(2, '0')}`
  const seq = String(inboundOrders.length + 1).padStart(6, '0')
  return `IN${ymd}${seq}`
}

export function nextTaskNo() {
  const d = new Date()
  const ymd = `${d.getFullYear()}${String(d.getMonth() + 1).padStart(2, '0')}${String(
    d.getDate(),
  ).padStart(2, '0')}`
  const seq = String(stockTasks.length + 1).padStart(6, '0')
  return `TASK${ymd}${seq}`
}

export function nextTxNo() {
  const d = new Date()
  const ymd = `${d.getFullYear()}${String(d.getMonth() + 1).padStart(2, '0')}${String(
    d.getDate(),
  ).padStart(2, '0')}`
  const seq = String(transactions.length + 1).padStart(6, '0')
  return `TX${ymd}${seq}`
}

export function timestamp() {
  return new Date().toISOString().slice(0, 19).replace('T', ' ')
}

